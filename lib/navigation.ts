/** Flat lookup: module id → NavModule */
export function getModuleById(id: string): NavModule | undefined {
  for (const domain of NAV_DOMAINS) {
    for (const group of domain.groups) {
      const m = group.modules.find((mod) => mod.id === id);
      if (m) return m;
    }
  }
  return undefined;
}

/** All modules as flat array */
export function getAllModules(): NavModule[] {
  return NAV_DOMAINS.flatMap((d) => d.groups.flatMap((g) => g.modules));
}
